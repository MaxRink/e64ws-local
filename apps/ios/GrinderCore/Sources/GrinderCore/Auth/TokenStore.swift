/// The owner token from `/db/e64local/token`, the second factor for every
/// local API route.
///
/// The value is never printed: `description` and `debugDescription` are
/// redacted so a token cannot leak through a log line, an error message or an
/// interpolation.  It is stored in the Keychain and nowhere else.
public struct OwnerToken: Sendable, Equatable {
    public static let byteLength = 32
    public static let hexLength = byteLength * 2

    public let value: String

    /// A freshly generated 256-bit token, lowercase hex.
    public static func generate() -> OwnerToken {
        var bytes = [UInt8](repeating: 0, count: byteLength)
        fillWithSecureRandom(&bytes)
        // The generated bytes are always valid hex, so this cannot fail.
        return OwnerToken(value: bytes.map { String(format: "%02x", $0) }.joined())!
    }

    /// Accept only the format the device writes: lowercase hex, no whitespace.
    public init?(value: String) {
        guard value.count == Self.hexLength,
              value.allSatisfy({ $0.isHexDigit && !$0.isUppercase })
        else {
            return nil
        }
        self.value = value
    }

    public var redacted: String { "«owner token withheld»" }

    public var description: String { redacted }
    public var debugDescription: String { redacted }
}

extension OwnerToken: CustomDebugStringConvertible {}

/// Fill `buffer` with cryptographically secure random bytes.
private func fillWithSecureRandom(_ buffer: inout [UInt8]) {
    #if canImport(Security)
    let status = buffer.withUnsafeMutableBytes { raw in
        SecRandomCopyBytes(kSecRandomDefault, raw.count, raw.baseAddress!)
    }
    if status == errSecSuccess { return }
    #endif
    // Fallback for a platform without Security; still unpredictable.
    for index in buffer.indices {
        buffer[index] = UInt8.random(in: UInt8.min...UInt8.max)
    }
}

/// Where an owner token is kept.  The app uses the Keychain; tests use memory.
public protocol TokenStore: Sendable {
    func load(for key: String) throws -> OwnerToken?
    func save(_ token: OwnerToken, for key: String) throws
    func delete(for key: String) throws
}

/// In-memory store for tests and for a device the owner has not yet saved.
public final class InMemoryTokenStore: TokenStore, @unchecked Sendable {
    private var storage: [String: String] = [:]
    private let lock = NSLock()

    public init() {}

    public func load(for key: String) throws -> OwnerToken? {
        lock.lock(); defer { lock.unlock() }
        return storage[key].flatMap(OwnerToken.init)
    }

    public func save(_ token: OwnerToken, for key: String) throws {
        lock.lock(); defer { lock.unlock() }
        storage[key] = token.value
    }

    public func delete(for key: String) throws {
        lock.lock(); defer { lock.unlock() }
        storage[key] = nil
    }
}

public enum TokenStoreError: Error, Equatable {
    case keychainUnavailable(String)
    case unexpectedStatus(String)
}

extension TokenStoreError: LocalizedError {
    public var errorDescription: String? {
        switch self {
        case .keychainUnavailable(let detail):
            return "The Keychain is not available: \(detail)"
        case .unexpectedStatus(let detail):
            return "The Keychain returned an unexpected error: \(detail)"
        }
    }
}

#if canImport(Security)
/// Keychain-backed store.  One item per device, `kSecAttrAccessibleWhenUnlockedThisDeviceOnly`
/// and no iCloud synchronisation: the token stays on this phone and is
/// unavailable to other devices or to a backgrounded app.
public final class KeychainTokenStore: TokenStore, @unchecked Sendable {
    private let service: String

    public init(service: String = "io.github.maxrink.e64local.owner-token") {
        self.service = service
    }

    private func baseQuery(for key: String) -> [String: Any] {
        [
            kSecClass as String: kSecClassGenericPassword,
            kSecAttrService as String: service,
            kSecAttrAccount as String: key,
        ]
    }

    public func load(for key: String) throws -> OwnerToken? {
        var query = baseQuery(for: key)
        query[kSecReturnData as String] = true
        query[kSecMatchLimit as String] = kSecMatchLimitOne

        var item: CFTypeRef?
        let status = SecItemCopyMatching(query as CFDictionary, &item)
        switch status {
        case errSecSuccess:
            guard let data = item as? Data,
                  let value = String(data: data, encoding: .utf8)
            else {
                return nil
            }
            return OwnerToken(value: value)
        case errSecItemNotFound:
            return nil
        case errSecInteractionNotAllowed, errSecMissingEntitlement:
            // Tests on a headless host cannot use the Keychain; the app always
            // can, so this is reported rather than silently ignored.
            throw TokenStoreError.keychainUnavailable("item locked or missing entitlement (\(status))")
        default:
            throw TokenStoreError.unexpectedStatus("SecItemCopyMatching(\(status))")
        }
    }

    public func save(_ token: OwnerToken, for key: String) throws {
        let data = Data(token.value.utf8)
        let query = baseQuery(for: key)

        var addQuery = query
        addQuery[kSecValueData as String] = data
        addQuery[kSecAttrAccessible as String] = kSecAttrAccessibleWhenUnlockedThisDeviceOnly
        addQuery[kSecAttrSynchronizable as String] = false

        let addStatus = SecItemAdd(addQuery as CFDictionary, nil)
        switch addStatus {
        case errSecSuccess:
            return
        case errSecDuplicateItem:
            let updateQuery: [String: Any] = [kSecValueData as String: data]
            let status = SecItemUpdate(query as CFDictionary, updateQuery as CFDictionary)
            guard status == errSecSuccess else {
                throw TokenStoreError.unexpectedStatus("SecItemUpdate(\(status))")
            }
        case errSecInteractionNotAllowed, errSecMissingEntitlement:
            throw TokenStoreError.keychainUnavailable("item locked or missing entitlement (\(addStatus))")
        default:
            throw TokenStoreError.unexpectedStatus("SecItemAdd(\(addStatus))")
        }
    }

    public func delete(for key: String) throws {
        let status = SecItemDelete(baseQuery(for: key) as CFDictionary)
        guard status == errSecSuccess || status == errSecItemNotFound else {
            throw TokenStoreError.unexpectedStatus("SecItemDelete(\(status))")
        }
    }
}
#endif
