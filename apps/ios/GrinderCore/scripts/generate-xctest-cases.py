#!/usr/bin/env python3
"""Generate one XCTest method per GrinderCore check case.

The cases are defined once, as data, in `GrinderCoreChecksKit`; the portable
harness (`swift run GrinderCoreChecks`) iterates them directly.  XCTest needs a
method per case, and Swift cannot synthesise methods from data, so this script
writes `Tests/GrinderCoreTests/GeneratedCases.swift` from the sources:

    python3 scripts/generate-xctest-cases.py

Rules the generator relies on, so that the mapping stays unambiguous:

  * every case is written as `CheckCase("literal name") { … }` with a literal
    name — no string interpolation in the name;
  * case names are unique across the kit.

`testNothingIsStale` in the generated file fails if the count drifts from
`allChecks().count`, and `testAllChecksAggregate` runs every case regardless.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
KIT = ROOT / "Sources" / "GrinderCoreChecksKit"
OUTPUT = ROOT / "Tests" / "GrinderCoreTests" / "GeneratedCases.swift"

CASE_RE = re.compile(r'CheckCase\(\s*"((?:[^"\\]|\\.)*)"', re.S)


def slug(name: str) -> str:
    return "test_" + re.sub(r"[^0-9A-Za-z]+", "_", name).strip("_")


def collect(text: str) -> list[str]:
    names: list[str] = []
    for match in CASE_RE.finditer(text):
        name = match.group(1)
        if "\\(" in name:
            raise ValueError(f"case name uses interpolation: {name!r}")
        names.append(name.replace('\\"', '"'))
    return names


def main() -> int:
    names: list[str] = []
    for source in sorted(KIT.glob("*.swift")):
        try:
            names.extend(collect(source.read_text(encoding="utf-8")))
        except ValueError as error:
            print(f"generate: {source.name}: {error}", file=sys.stderr)
            return 1

    seen: set[str] = set()
    slugs: set[str] = set()
    for name in names:
        if name in seen:
            print(f"generate: duplicate case name {name!r}", file=sys.stderr)
            return 1
        seen.add(name)
        method = slug(name)
        if method in slugs:
            print(f"generate: duplicate test method {method!r} for {name!r}", file=sys.stderr)
            return 1
        slugs.add(method)

    def literal(text: str) -> str:
        return text.replace("\\", "\\\\").replace('"', '\\"')

    lines = [
        "// Generated by scripts/generate-xctest-cases.py — do not edit.",
        "// One XCTest method per check case.  The bodies come from",
        "// GrinderCoreChecksKit, the same data the portable harness runs.",
        "#if canImport(XCTest)",
        "import XCTest",
        "import GrinderCoreChecksKit",
        "",
        "final class GeneratedCases: XCTestCase {",
        f"    /// The generator saw {len(names)} cases.",
        f"    static let generatedCaseCount = {len(names)}",
        "    /// The names the generator saw, in order.",
        "    static let generatedCaseNames = [",
    ]
    for name in names:
        lines.append(f'        "{literal(name)}",')
    lines += [
        "    ]",
        "",
    ]
    for name in names:
        lines += [
            f"    func {slug(name)}() async throws {{",
            f'        let checkCase = try requireCase("{literal(name)}")',
            "        do {",
            "            try await checkCase.body()",
            "        } catch {",
            '            XCTFail("\\(checkCase.name): \\(error)")',
            "        }",
            "    }",
            "",
        ]

    lines += [
        "    /// Look up one case by its exact name.",
        "    private func requireCase(_ name: String) throws -> CheckCase {",
        "        guard let found = allChecks().first(where: { $0.name == name }) else {",
        '            XCTFail("no check case named \\(name)")',
        '            throw CheckFailure(message: "missing case \\(name)", file: #filePath, line: #line)',
        "        }",
        "        return found",
        "    }",
        "",
        "    func testNothingIsStale() {",
        "        // If this fails, run scripts/generate-xctest-cases.py.",
        "        let current = allChecks().map(\\.name)",
        "        XCTAssertEqual(",
        "            Self.generatedCaseCount,",
        "            current.count,",
        '            "GeneratedCases.swift is stale; re-run scripts/generate-xctest-cases.py"',
        "        )",
        "        XCTAssertEqual(",
        "            Set(Self.generatedCaseNames),",
        "            Set(current),",
        '            "GeneratedCases.swift is stale; re-run scripts/generate-xctest-cases.py"',
        "        )",
        "    }",
        "",
        "    func testAllChecksAggregate() async throws {",
        "        var failures: [String] = []",
        "        for checkCase in allChecks() {",
        "            do {",
        "                try await checkCase.body()",
        "            } catch {",
        '                failures.append("\\(checkCase.name): \\(error)")',
        "            }",
        "        }",
        "        XCTAssertTrue(failures.isEmpty, failures.joined(separator: \"\\n\"))",
        "    }",
        "}",
        "#endif",
        "",
    ]
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"generate: wrote {OUTPUT.relative_to(ROOT)} with {len(names)} cases")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
