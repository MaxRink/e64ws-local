"""Owner-controlled local HTTP/WSS API client for the Mahlkönig E64 WS.

The client is deliberately local-only: it never calls the Mahlkönig cloud.
It uses the extracted firmware's HTTPS REST routes and TLS WebSocket endpoint.
TLS verification is enabled by default.  ``insecure=True`` is an explicit
escape hatch for the shipped self-signed certificate and should only be used
on an isolated owner-controlled network.

The module uses only the Python standard library for HTTPS/REST.  WSS support
requires the optional ``websocket-client`` package listed in
``tools/requirements.txt``.
"""

from __future__ import annotations

import json
import ssl
import urllib.error
import urllib.request
from dataclasses import dataclass
from http.cookiejar import CookieJar
from pathlib import Path
from typing import Any, Mapping

try:
    from .e64ws_protocol import (
        E64WSProtocol,
        HAZARDOUS_ACTIONS,
        HAZARDOUS_DIRECT_COMMANDS,
    )
except ImportError:  # direct ``python tools/e64ws_cli.py`` execution
    from e64ws_protocol import (
        E64WSProtocol,
        HAZARDOUS_ACTIONS,
        HAZARDOUS_DIRECT_COMMANDS,
    )


class E64WSAPIError(RuntimeError):
    """An HTTP, WebSocket, protocol, or firmware-level API error."""


@dataclass(frozen=True)
class RestResponse:
    """Raw REST response, retained so callers can inspect headers/status."""

    status: int
    headers: Mapping[str, str]
    body: bytes

    def json(self) -> Any:
        return json.loads(self.body.decode("utf-8"))

    def text(self) -> str:
        return self.body.decode("utf-8", errors="replace")


def _ssl_context(*, insecure: bool, ca_file: str | None) -> ssl.SSLContext:
    if insecure and ca_file:
        raise ValueError("choose insecure=True or ca_file, not both")
    if insecure:
        context = ssl._create_unverified_context()
        context.check_hostname = False
        return context
    return ssl.create_default_context(cafile=ca_file)


def _json_bytes(value: Any) -> bytes:
    return json.dumps(value, separators=(",", ":")).encode("utf-8")


class E64WSClient:
    """One local TLS-WebSocket session.

    A client can be constructed with an existing token or after
    :meth:`E64LocalAPI.login` has returned one.  Tokens are never included in
    exceptions or diagnostic strings generated by this class.
    """

    def __init__(
        self,
        host: str,
        token: str,
        *,
        insecure: bool = False,
        ca_file: str | None = None,
        port: int = 9997,
        timeout: float = 10.0,
        scheme: str = "wss",
    ) -> None:
        self.host = host.removeprefix("https://").removeprefix("http://").rstrip("/")
        self.token = token
        self.insecure = insecure
        self.ca_file = ca_file
        self.port = port
        self.timeout = timeout
        if scheme not in {"ws", "wss"}:
            raise ValueError("scheme must be ws or wss")
        self.scheme = scheme
        self._socket: Any = None

    @property
    def url(self) -> str:
        # The token must be in the vendor-defined query parameter.  Do not
        # log this property or expose it through repr/debug output.
        return f"{self.scheme}://{self.host}:{self.port}/?token={self.token}"

    def connect(self) -> None:
        if self._socket is not None:
            return
        try:
            import websocket  # type: ignore[import-not-found]
        except ImportError as exc:
            raise E64WSAPIError(
                "WSS requires websocket-client; install tools/requirements.txt"
            ) from exc

        sslopt: dict[str, Any] | None = {}
        if self.scheme == "ws":
            sslopt = None
        elif self.insecure:
            sslopt.update(cert_reqs=ssl.CERT_NONE, check_hostname=False)
        elif self.ca_file:
            sslopt.update(cert_reqs=ssl.CERT_REQUIRED, ca_certs=self.ca_file)
        else:
            sslopt.update(cert_reqs=ssl.CERT_REQUIRED, check_hostname=True)
        try:
            kwargs: dict[str, Any] = {"timeout": self.timeout}
            if sslopt is not None:
                kwargs["sslopt"] = sslopt
            self._socket = websocket.create_connection(self.url, **kwargs)
        except Exception as exc:  # websocket-client has several exception types
            raise E64WSAPIError(f"local WSS connection failed: {exc}") from exc

    def close(self) -> None:
        if self._socket is not None:
            try:
                self._socket.close()
            finally:
                self._socket = None

    def recv(self) -> dict[str, Any]:
        self.connect()
        try:
            value = json.loads(self._socket.recv())
        except Exception as exc:
            raise E64WSAPIError(f"invalid/local WSS receive failed: {exc}") from exc
        if not isinstance(value, dict):
            raise E64WSAPIError("local WSS returned a non-object JSON value")
        return value

    def _request_message(
        self,
        message: Mapping[str, Any],
        *,
        timeout: float | None = None,
        max_unrelated: int = 100,
    ) -> dict[str, Any]:
        """Send one message and wait for its matching response.

        Heartbeat pongs and unrelated asynchronous notifications are ignored;
        an excessive number of unrelated messages aborts to avoid an infinite
        wait on a firmware version with a different response contract.
        """

        self.connect()
        if timeout is not None and hasattr(self._socket, "settimeout"):
            self._socket.settimeout(timeout)
        request = dict(message)
        try:
            self._socket.send(json.dumps(request, separators=(",", ":")))
            unrelated = 0
            while True:
                response = self.recv()
                if response == {"pong": True}:
                    continue
                if E64WSProtocol.matches_response(request, response):
                    return response
                unrelated += 1
                if response.get("type") == "UnknownType":
                    return response
                if unrelated >= max_unrelated:
                    raise E64WSAPIError("too many unrelated local WSS messages")
        except E64WSAPIError:
            raise
        except Exception as exc:
            raise E64WSAPIError(f"local WSS request failed: {exc}") from exc

    def request_message(
        self,
        message: Mapping[str, Any],
        *,
        timeout: float | None = None,
        max_unrelated: int = 100,
        allow_hazardous: bool = False,
    ) -> dict[str, Any]:
        """Send a non-action raw message.

        Raw action envelopes are deliberately rejected here; callers must use
        :meth:`action`, which validates the recovered suffix and applies the
        hazardous-operation policy.
        """

        command_type = str(message.get("type", ""))
        if command_type == "GbsCreateReport":
            raise E64WSAPIError(
                "GbsCreateReport is a GrinderAction variant; use action('GbsCreateReport')"
            )
        if command_type == "GrinderAction" or command_type.startswith("GrinderAction"):
            raise E64WSAPIError(
                "raw GrinderAction envelopes are disabled; use action() so the hazardous-operation guard is applied"
            )
        if command_type in HAZARDOUS_DIRECT_COMMANDS and not allow_hazardous:
            raise E64WSAPIError(
                f"{command_type} is guarded; pass allow_hazardous=True only for an isolated owner-controlled test"
            )
        return self._request_message(
            message, timeout=timeout, max_unrelated=max_unrelated
        )

    def request(
        self,
        command_type: str,
        data: Any = None,
        *,
        protocol: E64WSProtocol | None = None,
        timeout: float | None = None,
        allow_hazardous: bool = False,
    ) -> dict[str, Any]:
        if command_type == "GbsCreateReport":
            raise E64WSAPIError(
                "GbsCreateReport is a GrinderAction variant; use action('GbsCreateReport')"
            )
        if command_type == "GrinderAction" or command_type.startswith("GrinderAction"):
            raise E64WSAPIError(
                "GrinderAction commands must use action() so the hazardous-operation guard is applied"
            )
        builder = protocol or E64WSProtocol()
        return self.request_message(
            builder.request(command_type, data),
            timeout=timeout,
            allow_hazardous=allow_hazardous,
        )

    def action(
        self,
        suffix: str,
        data: Mapping[str, Any] | None = None,
        *,
        action_type: str | None = None,
        allow_hazardous: bool = False,
        protocol: E64WSProtocol | None = None,
        timeout: float | None = None,
    ) -> dict[str, Any]:
        if suffix in HAZARDOUS_ACTIONS and not allow_hazardous:
            raise E64WSAPIError(
                f"{suffix} is guarded; pass allow_hazardous=True only for an isolated owner-controlled test"
            )
        builder = protocol or E64WSProtocol()
        return self._request_message(
            builder.action(suffix, data, action_type=action_type), timeout=timeout
        )


class E64LocalAPI:
    """Combined HTTPS REST and local WSS client.

    ``login`` establishes both the PHP cookie session and the WSS bearer token.
    A pre-existing WSS token can be supplied to the constructor when REST
    login is intentionally not used.
    """

    def __init__(
        self,
        host: str,
        *,
        insecure: bool = False,
        ca_file: str | None = None,
        token: str | None = None,
        timeout: float = 10.0,
        scheme: str = "wss",
        port: int = 9997,
        rest_port: int | None = None,
    ) -> None:
        self.host = host.removeprefix("https://").removeprefix("http://").rstrip("/")
        self.insecure = insecure
        self.ca_file = ca_file
        self.timeout = timeout
        if scheme not in {"ws", "wss"}:
            raise ValueError("scheme must be ws or wss")
        self.scheme = scheme
        self.port = port
        self.rest_port = rest_port if rest_port is not None else (443 if scheme == "wss" else 80)
        if self.rest_port < 1 or self.rest_port > 65535:
            raise ValueError("rest_port must be between 1 and 65535")
        self.cookies = CookieJar()
        self.protocol = E64WSProtocol()
        self._opener = urllib.request.build_opener(
            urllib.request.HTTPCookieProcessor(self.cookies),
            urllib.request.HTTPSHandler(
                context=_ssl_context(insecure=insecure, ca_file=ca_file)
            ),
        )
        self.token = token
        self._ws: E64WSClient | None = None

    @property
    def base_url(self) -> str:
        return f"{'https' if self.scheme == 'wss' else 'http'}://{self.host}:{self.rest_port}"

    @property
    def ws(self) -> E64WSClient:
        if not self.token:
            raise E64WSAPIError("no WSS token; call login() or provide token=")
        if self._ws is None:
            self._ws = E64WSClient(
                self.host,
                self.token,
                insecure=self.insecure,
                ca_file=self.ca_file,
                timeout=self.timeout,
                scheme=self.scheme,
                port=self.port,
            )
        return self._ws

    def close(self) -> None:
        if self._ws is not None:
            self._ws.close()

    def __enter__(self) -> "E64LocalAPI":
        return self

    def __exit__(self, *_: Any) -> None:
        self.close()

    def rest_raw(
        self,
        route: str,
        body: Any = None,
        *,
        method: str = "POST",
        headers: Mapping[str, str] | None = None,
        timeout: float | None = None,
    ) -> RestResponse:
        route = "/" + route.lstrip("/")
        payload = None if body is None else _json_bytes(body)
        request_headers = {"Accept": "application/json"}
        if payload is not None:
            request_headers["Content-Type"] = "application/json"
        request_headers.update(headers or {})
        request = urllib.request.Request(
            f"{self.base_url}/rest_api{route}",
            data=payload,
            headers=request_headers,
            method=method,
        )
        try:
            with self._opener.open(request, timeout=timeout or self.timeout) as response:
                return RestResponse(
                    response.status,
                    {str(k): str(v) for k, v in response.headers.items()},
                    response.read(),
                )
        except urllib.error.HTTPError as exc:
            detail = exc.read().decode("utf-8", errors="replace")
            raise E64WSAPIError(f"REST {route} returned HTTP {exc.code}: {detail}") from exc
        except urllib.error.URLError as exc:
            raise E64WSAPIError(f"local REST request failed for {route}: {exc.reason}") from exc

    @staticmethod
    def _decode(response: RestResponse) -> Any:
        if not response.body:
            return None
        try:
            return response.json()
        except (UnicodeDecodeError, json.JSONDecodeError):
            return response.text()

    def rest(self, route: str, body: Any = None, *, method: str = "POST") -> Any:
        return self._decode(self.rest_raw(route, body, method=method))

    def login(self, role: str, password: str) -> Any:
        response = self.rest_raw("login", {"userRole": role, "password": password})
        authorization = next(
            (
                value
                for key, value in response.headers.items()
                if key.lower() == "authorization"
            ),
            "",
        )
        if not authorization.startswith("Bearer "):
            raise E64WSAPIError("REST login returned no bearer token")
        self.token = authorization.removeprefix("Bearer ").strip()
        if self._ws is not None:
            self._ws.close()
            self._ws = None
        return self._decode(response)

    def ping(self) -> Any:
        return self.rest("ping")

    def check_session(self) -> Any:
        return self.rest("check_session")

    def update_session(self) -> Any:
        return self.rest("update_session")

    def logout(self) -> Any:
        value = self.rest("logout")
        self.close()
        self.token = None
        return value

    def machine_info(self) -> Any:
        return self.rest("get_machine_info")

    def reboot(self, *, allow_hazardous: bool = False) -> Any:
        if not allow_hazardous:
            raise E64WSAPIError(
                "reboot is guarded; pass allow_hazardous=True only for an isolated owner-controlled test"
            )
        return self.rest("reboot")

    def firmware_update_state(self) -> Any:
        return self.rest("get_fw_update_state")

    def request_onboarding(self, data: Mapping[str, Any]) -> Any:
        return self.rest("request_onboarding", dict(data))

    def scan_wifi(self) -> Any:
        return self.rest("scan_wifi")

    def wifi_info(self) -> Any:
        return self.rest("get_wifi_info")

    def download_database(self, output: str | Path | None = None) -> bytes:
        data = self.rest_raw("download_database").body
        if output is not None:
            Path(output).write_bytes(data)
        return data

    def download_machine_logs(self, output: str | Path | None = None) -> bytes:
        data = self.rest_raw("download_machine_logs").body
        if output is not None:
            Path(output).write_bytes(data)
        return data

    def ws_request(
        self,
        command_type: str,
        data: Any = None,
        *,
        allow_hazardous: bool = False,
    ) -> dict[str, Any]:
        if command_type == "GrinderAction" or command_type.startswith("GrinderAction"):
            raise E64WSAPIError(
                "GrinderAction commands must use ws_action() so the hazardous-operation guard is applied"
            )
        return self.ws.request(
            command_type,
            data,
            protocol=self.protocol,
            allow_hazardous=allow_hazardous,
        )

    def ws_action(
        self,
        suffix: str,
        data: Mapping[str, Any] | None = None,
        *,
        action_type: str | None = None,
        allow_hazardous: bool = False,
    ) -> dict[str, Any]:
        return self.ws.action(
            suffix,
            data,
            action_type=action_type,
            allow_hazardous=allow_hazardous,
            protocol=self.protocol,
        )

    def driver_state(self) -> dict[str, Any]:
        return self.ws_request("RequestDriverState")

    def driver_config(self) -> dict[str, Any]:
        return self.ws_request("RequestDriverConfig")

    def gbs_report(self) -> dict[str, Any]:
        return self.ws_action("GbsCreateReport")


