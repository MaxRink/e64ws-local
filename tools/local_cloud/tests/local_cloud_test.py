"""Offline tests for the local-cloud skeleton (D01-D10).

Naming note
-----------

The files here are named ``*_test.py`` rather than ``test_*.py`` on purpose.
``tools/run_tests.py`` fails the whole repository run when a ``test_*.py`` file
is not registered in its ``SUITES`` table, and this task may not edit that file.
So the module is discoverable with ``-p '*_test.py'`` and runnable by module
path, and registering it in ``SUITES`` stays a one-line follow-up for whoever
owns ``tools/run_tests.py``.  See ``tools/local_cloud/tests/README.md``.

What is covered
---------------

* every D01-D10 path answers with the status the design implies, including the
  five 501 refusals and the exact ``unknown — needs capture`` marker;
* the 501 body carries a stable ``reason`` token and the D-id;
* the D01 visibility rule (approved sources only, > 10 000 ms, cursor filter);
* the audit trail: a row per device request with fingerprint and status, an
  append-only table that refuses UPDATE and DELETE, and the JSONL mirror;
* redaction of ``productionWifiSsid``/``productionWifiPassword`` before storage;
* one mutual-TLS handshake with certificates generated by ``openssl`` (skipped
  when ``openssl`` is absent), including the unknown-certificate refusal;
* the CLI entry point in a subprocess, so the runnable path is not just an
  import.
"""

