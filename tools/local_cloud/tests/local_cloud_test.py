class BrewEventVisibilityTests(ServiceTestCase):
    """The D01 server rule from the design: approved, > 10 s, cursor ordered."""

    def poll(self, since: datetime) -> list[dict]:
        body = {"payload": {"grinderId": "ignored", "deviceDateRange": {"from": iso(since)}}}
        status, payload, _ = self.call("POST", f"{DEVICE}/brew-event/find", body)
        self.assertEqual(status, 200, payload)
        self.assertIsInstance(payload, list)
        return payload  # type: ignore[return-value]

    def test_short_events_are_filtered_by_the_documented_10s_gate(self) -> None:
        now = datetime.now(timezone.utc)
        self.server.store.add_brew_event(device_id="local-dev-device", duration_ms=9_600, mass_mg=18_000)
        self.server.store.add_brew_event(device_id="local-dev-device", duration_ms=25_400, mass_mg=18_200)
        events = self.poll(now - timedelta(minutes=1))
        self.assertEqual(len(events), 1)
        self.assertEqual(events[0]["payload"]["duration"], 25_400)

    def test_unapproved_events_are_invisible(self) -> None:
        self.server.store.add_brew_event(
            device_id="local-dev-device", duration_ms=25_000, approved=False
        )
        self.assertEqual(self.poll(datetime.now(timezone.utc) - timedelta(minutes=5)), [])

    def test_cursor_filters_and_order_is_ascending(self) -> None:
        base = datetime.now(timezone.utc).replace(microsecond=0) - timedelta(minutes=10)
        later = base + timedelta(minutes=4)
        self.server.store.add_brew_event(
            device_id="local-dev-device", duration_ms=20_000, cloud_date=iso(later), event_uuid="later"
        )
        self.server.store.add_brew_event(
            device_id="local-dev-device", duration_ms=20_000, cloud_date=iso(base), event_uuid="earlier"
        )
        events = self.poll(base - timedelta(seconds=1))
        self.assertEqual([item["payload"]["eventUuid"] for item in events], ["earlier", "later"])
        # A cursor after both events yields nothing.
        self.assertEqual(self.poll(later + timedelta(minutes=1)), [])

    def test_element_shape_uses_the_recorded_literals(self) -> None:
        self.server.store.add_brew_event(
            device_id="local-dev-device",
            duration_ms=25_000,
            mass_mg=18_200,
            grind_event_uuid="grind-1",
            source="scale",
        )
        events = self.poll(datetime.now(timezone.utc) - timedelta(minutes=1))
        payload = events[0]["payload"]
        self.assertEqual(payload["brewer"], "scale")
        self.assertEqual(payload["groupNumber"], "0")
        self.assertEqual(payload["doseType"], "MassType")
        self.assertTrue(payload["validity"])
        self.assertEqual(payload["mass"], 18_200)
        self.assertEqual(payload["grindEventUuid"], "grind-1")
        self.assertNotIn("volume", payload, "volume is lm-only and must not be invented")

    def test_stored_cloud_date_is_normalised_so_the_cursor_is_sound(self) -> None:
        admin = {"Authorization": "Bearer test-admin-token-not-a-credential"}
        # 12:00 at +02:00 is 10:00 UTC; the cursor at 10:30 UTC must exclude it.
        status, payload, _ = self.call(
            "POST",
            "/admin/v1/brew-events",
            {
                "deviceId": "local-dev-device",
                "durationMs": 25_000,
                "cloudDate": "2026-05-01T12:00:00+02:00",
            },
            headers=admin,
        )
        self.assertEqual(status, 200)
        self.assertEqual(payload["brewEvent"]["cloud_date"], "2026-05-01T10:00:00Z")  # type: ignore[index]
        later = datetime(2026, 5, 1, 10, 30, tzinfo=timezone.utc)
        self.assertEqual(self.poll(later), [])
        earlier = datetime(2026, 5, 1, 9, 30, tzinfo=timezone.utc)
        self.assertEqual(len(self.poll(earlier)), 1)

    def test_admin_rejects_an_unparseable_cloud_date(self) -> None:
        admin = {"Authorization": "Bearer test-admin-token-not-a-credential"}
        status, payload, _ = self.call(
            "POST",
            "/admin/v1/brew-events",
            {"deviceId": "local-dev-device", "durationMs": 25_000, "cloudDate": "yesterday"},
            headers=admin,
        )
        self.assertEqual(status, 400)
        self.assertEqual(payload["error"]["reason"], "cloud-date-unparseable")  # type: ignore[index]


class RedactionTests(ServiceTestCase):
    """Design §8: Wi-Fi credentials never reach the database."""

    def test_device_settings_wifi_keys_are_redacted_before_persistence(self) -> None:
        body = {
            "eventType": "DEVICE_SETTINGS",
            "eventUuid": "settings-1",
            "configuration": {
                "productionWifiSsid": "owner-network",
                "productionWifiPassword": "not-a-real-password",
                "grinderSn": "SN-1",
            },
        }
        status, _, _ = self.call("POST", f"{DEVICE}/device-event/fire", body)
        self.assertEqual(status, 200)
        with self.server.store.session() as connection:
            stored = connection.execute("SELECT payload, type FROM device_event").fetchone()
        text = stored["payload"]
        self.assertNotIn("owner-network", text)
        self.assertNotIn("not-a-real-password", text)
        self.assertIn("<redacted>", text)
        self.assertEqual(stored["type"], "DEVICE_SETTINGS")
        # A secret-looking key the design does not name is redacted too.
        self.assertEqual(store.redact({"apiToken": "x"}), {"apiToken": "<redacted>"})
        self.assertEqual(store.redact({"grinderSn": "SN-1"}), {"grinderSn": "SN-1"})


class AuditTests(ServiceTestCase):
    """Design §8: append-only, per-request, with fingerprint and status."""

    def test_a_device_request_writes_an_audit_row_and_a_jsonl_line(self) -> None:
        status, _, _ = self.call("GET", f"{DEVICE}/system/time")
        self.assertEqual(status, 501)
        rows = self.server.store.audit_rows(limit=10)
        self.assertEqual(len(rows), 1)
        row = rows[0]
        self.assertEqual(row["actor"], "device:local-dev-device")
        self.assertEqual(row["subject"], f"{DEVICE}/system/time")
        detail = json.loads(row["detail"])
        self.assertEqual(detail["status"], 501)
        self.assertEqual(detail["d_id"], "D10")
        self.assertEqual(detail["reason"], "timestamp-format-unknown")
        self.assertEqual(detail["identity_source"], "anonymous")
        lines = self.audit_path.read_text(encoding="utf-8").splitlines()
        self.assertEqual(len(lines), 1)
        self.assertEqual(json.loads(lines[0])["subject"], f"{DEVICE}/system/time")

    def test_the_audit_table_refuses_update_and_delete(self) -> None:
        self.call("GET", f"{DEVICE}/system/time")
        with self.server.store.session() as connection:
            with self.assertRaises(Exception) as update:
                connection.execute("UPDATE audit SET actor = 'forged'")
            self.assertIn("append-only", str(update.exception))
            with self.assertRaises(Exception) as delete:
                connection.execute("DELETE FROM audit")
            self.assertIn("append-only", str(delete.exception))
        self.assertEqual(len(self.server.store.audit_rows()), 1)

    def test_unverified_fields_reach_the_audit_row(self) -> None:
        status, _, headers = self.call(
            "POST", f"{DEVICE}/device-event/fire", {"eventType": "GRIND_COMPLETE"}
        )
        self.assertEqual(status, 200)
        self.assertIn("D05.response.body", headers[service.UNVERIFIED_HEADER.lower()])
        newest = self.server.store.audit_rows(limit=1)[0]
        detail = json.loads(newest["detail"])
        self.assertIn("D05.response.body", detail["unverified_fields"])

    def test_admin_requests_are_audited_without_a_bearer_token_leak(self) -> None:
        status, _, _ = self.call("POST", "/admin/v1/devices", {"deviceId": "d-1"})
        self.assertEqual(status, 401)
        rows = self.server.store.audit_rows(limit=5)
        self.assertEqual(rows[0]["actor"], "anonymous")
        self.assertEqual(json.loads(rows[0]["detail"])["status"], 401)
        self.assertNotIn("test-admin-token-not-a-credential", rows[0]["detail"])


