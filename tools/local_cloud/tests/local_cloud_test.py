def request(
    port: int,
    method: str,
    path: str,
    body: dict | None = None,
    *,
    headers: dict[str, str] | None = None,
    context: ssl.SSLContext | None = None,
    scheme: str = "http",
    timeout: float = 10.0,
) -> tuple[int, dict | list | str, dict[str, str]]:
    """One HTTP(S) call; returns status, decoded body and lower-cased headers."""

    if scheme == "https":
        connection: http.client.HTTPConnection = http.client.HTTPSConnection(
            "127.0.0.1", port, timeout=timeout, context=context
        )
    else:
        connection = http.client.HTTPConnection("127.0.0.1", port, timeout=timeout)
    try:
        data = json.dumps(body).encode() if body is not None else None
        all_headers = {"Content-Type": "application/json"}
        all_headers.update(headers or {})
        connection.request(method, path, body=data, headers=all_headers)
        response = connection.getresponse()
        raw = response.read()
        returned = {key.lower(): value for key, value in response.getheaders()}
        content_type = returned.get("content-type", "")
        if raw and "json" in content_type:
            payload: dict | list | str = json.loads(raw)
        else:
            payload = raw.decode("utf-8", "replace")
        return response.status, payload, returned
    finally:
        connection.close()


def iso(moment: datetime) -> str:
    return moment.astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


class ServiceTestCase(unittest.TestCase):
    """Shared fixture: one server on an ephemeral port with a temp database."""

    server: service.LocalCloudServer

    def setUp(self) -> None:
        self.scratch = tempfile.TemporaryDirectory(ignore_cleanup_errors=True, prefix="local-cloud-test-")
        self.addCleanup(self.scratch.cleanup)
        self.db_path = Path(self.scratch.name) / "local-cloud.sqlite3"
        self.audit_path = Path(self.scratch.name) / "audit.jsonl"
        self.server = service.LocalCloudServer(
            db_path=self.db_path,
            audit_file=self.audit_path,
            port=0,
            allow_anonymous=True,
            admin_token="test-admin-token-not-a-credential",
        ).start()
        self.addCleanup(self.server.close)

    def call(
        self, method: str, path: str, body: dict | None = None, **kwargs: object
    ) -> tuple[int, dict | list | str, dict[str, str]]:
        return request(self.server.port, method, path, body, **kwargs)  # type: ignore[arg-type]

    def refuse(
        self, method: str, path: str, body: dict | None = None
    ) -> dict[str, object]:
        status, payload, headers = self.call(method, path, body)
        self.assertEqual(status, 501, payload)
        self.assertIsInstance(payload, dict)
        error = payload["error"]  # type: ignore[index]
        self.assertEqual(error["code"], "unsupported")
        self.assertIn(contract.UNKNOWN_MARKER, error["message"])
        self.assertIn("D", error["d_id"])
        self.assertTrue(error["reason"])
        self.assertEqual(error["status"], 501)
        self.assertTrue(headers.get(service.UNVERIFIED_HEADER.lower()))
        return error


