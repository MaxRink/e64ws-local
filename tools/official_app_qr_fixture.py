#!/usr/bin/env python3
"""Generate the reserved synthetic QR fixture used by the Android audit.

The stock app's QR format is not fully recovered.  This tool creates a
non-secret candidate payload for camera/transport experiments; it is not a
claim about the vendor's production QR schema.  Non-fixture payloads require
an explicit opt-in so a real credential or device QR is not generated by
accident during a repeatable audit.
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
from pathlib import Path


DEFAULT_PAYLOAD = "https://192.168.4.1/ABC123"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output",
        required=True,
        type=Path,
        help="PNG output path; keep generated images outside Git",
    )
    parser.add_argument("--payload", default=DEFAULT_PAYLOAD)
    parser.add_argument(
        "--allow-nonfixture",
        action="store_true",
        help="permit a caller-supplied payload other than the reserved fixture",
    )
    args = parser.parse_args(argv)

    if args.payload != DEFAULT_PAYLOAD and not args.allow_nonfixture:
        parser.error(
            "only the reserved synthetic payload is enabled by default; "
            "use --allow-nonfixture only for an explicitly authorized lab input"
        )

    encoder = shutil.which("qrencode")
    if encoder is None:
        parser.error("qrencode is required; install it with: brew install qrencode")

    args.output.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        [
            encoder,
            "-8",
            "-l",
            "H",
            "-s",
            "18",
            "-m",
            "6",
            "-o",
            str(args.output),
            args.payload,
        ],
        check=True,
    )
    print(f"wrote synthetic QR fixture: {args.output}")
    print(
        "payload class: "
        f"{'reserved-fixture' if args.payload == DEFAULT_PAYLOAD else 'caller-supplied'}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
